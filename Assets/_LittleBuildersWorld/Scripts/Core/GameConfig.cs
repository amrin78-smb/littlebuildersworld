using System;
using LittleBuildersWorld.Audio;
using LittleBuildersWorld.Progression;
using LittleBuildersWorld.Vehicles;
using UnityEngine;

namespace LittleBuildersWorld.Core
{
    /// <summary>A vehicle colour scheme. Index 0 is each vehicle's own factory paint and is always available.</summary>
    [Serializable]
    public sealed class PaintScheme
    {
        public string id;
        [Tooltip("Unlock id that makes this paint available; empty = always available.")] public string unlockId;
        public Color primary = Color.yellow;
        public Color secondary = Color.white;
        public Sprite swatch;
    }

    /// <summary>
    /// Game-wide data loaded from Resources at startup: vehicles, unlocks, paints, audio and HUD icons.
    /// Generated by the setup pipeline; edit values here rather than in scripts.
    /// </summary>
    [CreateAssetMenu(menuName = "Little Builders World/Game Config", fileName = "LBW_GameConfig")]
    public sealed class GameConfig : ScriptableObject
    {
        public const string ResourcePath = "LBW_GameConfig";

        public VehicleProfile[] vehicles = Array.Empty<VehicleProfile>();
        public UnlockDefinition[] unlocks = Array.Empty<UnlockDefinition>();
        public PaintScheme[] paints = Array.Empty<PaintScheme>();
        public AudioLibrary audio;

        [Header("HUD icons")]
        public Sprite iconScoop;
        public Sprite iconDump;
        public Sprite iconLoad;
        public Sprite iconUnload;
        public Sprite iconStar;

        [Header("Frame rate")]
        [Tooltip("Requested frame rate. Budget phones deliver less; see ANDROID_BUILD_GUIDE.md.")] public int targetFrameRate = 60;

        public Sprite IconFor(ActionIcon icon)
        {
            switch (icon)
            {
                case ActionIcon.Scoop: return iconScoop;
                case ActionIcon.Dump: return iconDump;
                case ActionIcon.Load: return iconLoad;
                case ActionIcon.Unload: return iconUnload;
                default: return null;
            }
        }

        public VehicleProfile FindVehicle(string id)
        {
            foreach (VehicleProfile v in vehicles)
            {
                if (v != null && v.id == id) return v;
            }
            return null;
        }
    }
}
